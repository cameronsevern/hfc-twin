//! Streets, homes and a region over many plants. A new schema rather than an edit to `Plant`, whose version
//! holds (invariant 3), for what Tasks 01 and 02 deferred. See `docs/tasks/08-design-and-records.md`.

use schemars::JsonSchema;
use serde::{Deserialize, Serialize};

use crate::common::{LonLat, Origin, ProfileId, ServiceGroupId};
use crate::plant::Installation;

/// Version of this schema. Version 2 added `Region::fiber_ref`, and version 3 `DesignControls::rules_id` and
/// `DesignControls::mode`; neither changed anything before it. Maps share the version, and didn't change at all.
pub const SCHEMA_VERSION: &str = "3";

/// Brings a region from an earlier version to this one. Versions 2 and 3 only added optional fields.
pub fn migrate(mut region: Region) -> Result<Region, String> {
    match region.schema_version.as_str() {
        "1" | "2" | "3" => {
            region.schema_version = SCHEMA_VERSION.to_string();
            Ok(region)
        }
        other => Err(format!("no migration from region schema version {other}")),
    }
}

/// Brings a map from an earlier version to this one. A map is the same in versions 1 to 3.
pub fn migrate_map(mut map: StreetMap) -> Result<StreetMap, String> {
    match map.schema_version.as_str() {
        "1" | "2" | "3" => {
            map.schema_version = SCHEMA_VERSION.to_string();
            Ok(map)
        }
        other => Err(format!("no migration from map schema version {other}")),
    }
}

/// A layout family: held out by family, never by random sample, when evaluating models (`docs/DESIGN.md`).
#[derive(
    Serialize, Deserialize, JsonSchema, Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash,
)]
pub enum LayoutFamily {
    /// Short blocks on a grid, dense lots, aerial.
    UrbanGrid,
    /// Arterials and cul-de-sacs, underground.
    Suburban,
    /// Long roads, few homes, aerial.
    Rural,
}

/// Where a map came from.
#[derive(Serialize, Deserialize, JsonSchema, Debug, Clone, PartialEq)]
pub enum MapSource {
    /// Generated by this project: the geography is as invented as the plant.
    Generated {
        /// Its family.
        family: LayoutFamily,
        /// The seed that drew it.
        seed: u64,
    },
    /// OpenStreetMap: real geography, with an invented plant on it.
    OpenStreetMap {
        /// Attribution the license requires.
        attribution: String,
    },
}

/// A road a cable can follow.
#[derive(Serialize, Deserialize, JsonSchema, Debug, Clone, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct Street {
    /// Stable identifier.
    pub id: String,
    /// Its centerline.
    pub points: Vec<LonLat>,
    /// How plant runs along it.
    pub installation: Installation,
}

/// A home passed.
#[derive(Serialize, Deserialize, JsonSchema, Debug, Clone, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct Home {
    /// Stable identifier.
    pub id: String,
    /// Where it is.
    pub geo: LonLat,
}

/// The geography a design starts from.
#[derive(Serialize, Deserialize, JsonSchema, Debug, Clone, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct StreetMap {
    /// Version of this schema.
    pub schema_version: String,
    /// Stable identifier.
    pub id: String,
    /// Where it came from.
    pub source: MapSource,
    /// Roads.
    pub streets: Vec<Street>,
    /// Homes passed.
    pub homes: Vec<Home>,
    /// Where fiber comes from: the hub's site.
    pub headend: LonLat,
}

/// A node held where the user put it. The optimizer re-solves around it (`docs/DESIGN.md`, "Reactivity").
#[derive(Serialize, Deserialize, JsonSchema, Debug, Clone, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct PinnedNode {
    /// Where it goes.
    pub geo: LonLat,
}

/// What a designer can turn (`docs/DESIGN.md`, "Reactivity").
#[derive(Serialize, Deserialize, JsonSchema, Debug, Clone, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct DesignControls {
    /// Target homes per node. Never above the profile's `max_homes_passed`.
    pub homes_per_node: u32,
    /// Cascade limit, if tighter than the profile's.
    pub cascade_limit: Option<u8>,
    /// Share of homes with a modem, 0 to 1.
    pub take_rate: f64,
    /// Share of modems that are D3.0, 0 to 1.
    pub d30_share: f64,
    /// Longest drop, feet.
    pub max_drop_ft: f64,
    /// Nodes held in place. Their service groups are numbered from these first.
    pub pinned_nodes: Vec<PinnedNode>,
    /// Seed for take rate and generation draws.
    pub seed: u64,
    /// The design rules to design by, by id. Given, the version 2 designer runs; absent, version 1's. Version 3.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub rules_id: Option<String>,
    /// How the version 2 designer works. Absent is `Greenfield`. Version 3.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub mode: Option<DesignMode>,
    /// Build the nodes the rules' cost ceiling puts over it, and still mark them and their homes as over it. Off, a
    /// node over the ceiling isn't built. Version 3.
    #[serde(default, skip_serializing_if = "std::ops::Not::not")]
    pub build_over_ceiling: bool,
}

/// How the version 2 designer works (`docs/tasks/23-as-built-designer.md`). Version 3.
#[derive(Serialize, Deserialize, JsonSchema, Debug, Clone, PartialEq)]
pub enum DesignMode {
    /// Designed new, to the target profile under the rules.
    Greenfield,
    /// Designed under legacy rules and a legacy profile, then upgraded in place to the target profile under the rules'
    /// upgrade moves (`design::migrate`).
    LegacyThenUpgrade {
        /// The legacy rules, by id.
        legacy_rules_id: String,
        /// The legacy profile.
        legacy_profile_ref: ProfileId,
    },
}

impl Default for DesignControls {
    fn default() -> Self {
        DesignControls {
            homes_per_node: 250,
            cascade_limit: None,
            take_rate: 0.6,
            d30_share: 0.3,
            max_drop_ft: 250.0,
            pinned_nodes: Vec::new(),
            seed: 1,
            rules_id: None,
            mode: None,
            build_over_ceiling: false,
        }
    }
}

/// One node in a region.
#[derive(Serialize, Deserialize, JsonSchema, Debug, Clone, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct RegionNode {
    /// Its service group, whose plant is its own file.
    pub service_group: ServiceGroupId,
    /// The profile it runs.
    pub profile_ref: ProfileId,
    /// Homes it passes.
    pub homes_passed: u32,
}

/// A region: many nodes on one map.
#[derive(Serialize, Deserialize, JsonSchema, Debug, Clone, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct Region {
    /// Version of this schema.
    pub schema_version: String,
    /// Stable identifier.
    pub id: String,
    /// The map it's on.
    pub map_id: String,
    /// Whether it's simulated or real (invariant 11).
    pub origin: Origin,
    /// Its nodes.
    pub nodes: Vec<RegionNode>,
    /// The id of its fiber plant, a `schema::fiber::FiberPlant`. Version 2.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub fiber_ref: Option<String>,
}
