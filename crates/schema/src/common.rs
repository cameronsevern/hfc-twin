/// For `skip_serializing_if` on a flag that defaults to false, so a version 1 document round-trips unchanged.
pub fn is_false(value: &bool) -> bool {
    !*value
}

/// Simulated time in seconds, passed in and never read from the system clock
/// (invariant 4). t = 0 is midnight on the simulated day (§8).
#[derive(
    Serialize, Deserialize, JsonSchema, Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash,
)]
#[serde(transparent)]
pub struct Timestamp(pub i64);

/// A complex number, used for pre-eq and channel-estimate coefficients (§5.3–§5.5).
#[derive(Serialize, Deserialize, JsonSchema, Debug, Clone, Copy, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct Complex {
    /// Real part, dimensionless.
    pub re: f64,
    /// Imaginary part, dimensionless.
    pub im: f64,
}

/// A geographic position.
#[derive(Serialize, Deserialize, JsonSchema, Debug, Clone, Copy, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct LonLat {
    /// Longitude in degrees, WGS 84.
    pub lon_deg: f64,
    /// Latitude in degrees, WGS 84.
    pub lat_deg: f64,
}

/// Whether a plant or observation is simulated or measured (invariant 11).
#[derive(Serialize, Deserialize, JsonSchema, Debug, Clone, Copy, PartialEq, Eq)]
pub enum Origin {
    /// Generated by this project; never to be presented as real.
    Synthetic,
    /// Measured on, or imported from, a real network.
    Field,
}
